const SVG_NS = "http://www.w3.org/2000/svg";

/// <svg> d'une icône (taille en px). Décorative par défaut (aria-hidden) : le
/// libellé accessible est porté par le bouton ou le lien qui la contient.
export function icon(name, { size = 18, cls = "" } = {}) {
  const svg = document.createElementNS(SVG_NS, "svg");
  for (const [k, v] of Object.entries({
    class: cls ? `ico ${cls}` : "ico",
    viewBox: "0 0 24 24",
    width: String(size),
    height: String(size),
    fill: "none",
    stroke: "currentColor",
    "stroke-width": "2",
    "stroke-linecap": "round",
    "stroke-linejoin": "round",
    "aria-hidden": "true",
    focusable: "false",
  })) {
    svg.setAttribute(k, v);
  }
  // Contenu statique de ce module (jamais de donnée distante).
  svg.innerHTML = PATHS[name] || "";
  return svg;
}
